export function t(key, values = {}) {
  let value = language.value === "ar" ? ar[key] || key : key;
  for (const [name, replacement] of Object.entries(values))
    value = value.replaceAll(`{${name}}`, replacement ?? "");
  return value;
}

export function applyLanguage() {
  const value = language.value;
  localStorage.setItem("nightjar-language", value);
  document.cookie = `nightjar_language=${value}; Path=/; Max-Age=31536000; SameSite=Lax`;
  document.documentElement.lang = value;
  document.documentElement.dir = value === "ar" ? "rtl" : "ltr";
}

export async function setLanguage(value) {
  if (!["ar", "en"].includes(value) || value === language.value) return;
  const previous = language.value;
  language.value = value;
  applyLanguage();
  try {
    const response = await fetch("/api/method/nightjar_learning.localization.set_language", {
      method: "POST",
      credentials: "same-origin",
      headers: {
        "Content-Type": "application/json",
        ...(boot.csrf_token ? { "X-Frappe-CSRF-Token": boot.csrf_token } : {}),
      },
      body: JSON.stringify({ language: value }),
    });
    if (!response.ok) throw new Error(t("The request failed. Please try again."));
    location.reload();
  } catch (error) {
    language.value = previous;
    applyLanguage();
    throw error;
  }
}

