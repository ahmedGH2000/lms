def registry_runner(tmp_path):
    import sys
    (tmp_path / 'sites').mkdir()
    (tmp_path / 'env/bin').mkdir(parents=True)
    (tmp_path / 'env/bin/python').symlink_to(sys.executable)
    script = (Path(__file__).parents[1] / 'deploy/init.sh').read_text()
    function = script.split('register_apps() {', 1)[1].split('\n}', 1)[0]
    return 'set -e\nregister_apps() {' + function + '\n}\nregister_apps "$@"'


def test_registry_without_newline_preserves_other_apps(tmp_path):
    runner = registry_runner(tmp_path)
    path = tmp_path / 'sites/apps.txt'
    path.write_text('frappe\npayments\ncustom_app\nlms')
    for _ in range(2):
        subprocess.run(['bash', '-c', runner, 'registry', 'nightjar_learning'], cwd=tmp_path, check=True)
        assert path.read_text() == 'frappe\npayments\ncustom_app\nlms\nnightjar_learning\n'


def test_registry_repairs_and_backs_up_observed_corruption(tmp_path):
    runner = registry_runner(tmp_path)
    path = tmp_path / 'sites/apps.txt'
    original = 'frappe\npayments\nlmsnightjar_learning\nnightjar_learning\n'
    path.write_text(original)
    for _ in range(2):
        subprocess.run(['bash', '-c', runner, 'registry'], cwd=tmp_path, check=True)
        assert path.read_text() == 'frappe\npayments\nlms\nnightjar_learning\n'
        assert (tmp_path / 'sites/apps.txt.before-nightjar-repair').read_text() == original


def lifecycle_fixture(tmp_path):
    """Real shell/Python/file operations; external services/build commands are stubs."""
    import os
    import sys
    work = tmp_path / 'work'
    bench = work / 'bench'
    binary = tmp_path / 'bin'
    binary.mkdir()
    (bench / 'env/bin').mkdir(parents=True)
    (bench / 'env/bin/python').symlink_to(sys.executable)
    (bench / 'sites').mkdir()
    (bench / 'sites/apps.txt').write_text('frappe\npayments\nlmsnightjar_learning\n')
    (bench / '.nightjar-dependencies').touch()
    (bench / 'Procfile').write_text('web: bench serve\n')
    for name in ('frappe', 'payments', 'lms', 'nightjar_learning'):
        package = bench / 'apps' / name / name
        package.mkdir(parents=True)
        (package / '__init__.py').touch()
        (package / 'modules.txt').write_text(name+'\n')
    source = tmp_path / 'source'
    source.mkdir()
    (source / 'sentinel.txt').write_text('copied source')
    # Patches have separate real-Git coverage; this fixture checks shell lifecycle.
    (source / 'deploy/patches').mkdir(parents=True)
    (source / 'deploy/patches/test.patch').write_text('asset revision fixture')
    (source / 'deploy/apply_upstream_patches.py').write_text('pass\n')
    (source / 'deploy/verify_release.py').write_text('pass\n')
    stub = '#!'+sys.executable+'\n'+'''import json, os, sys
from pathlib import Path
tool = Path(sys.argv[0]).name
args = sys.argv[1:]
with open(os.environ['CALL_LOG'], 'a') as f:
    f.write(json.dumps([tool, *args])+'\\n')
if tool == 'bench':
    assert 'lmsnightjar_learning' not in Path('sites/apps.txt').read_text()
    if args[0] == 'new-site':
        folder = Path('sites') / args[1]
        folder.mkdir()
        (folder / 'site_config.json').write_text('{}')
    if args[0] == 'build' and os.environ.get('FAIL_BUILD') == '1':
        sys.exit(9)
'''
    for name in ('bench', 'node', 'npm', 'yarn'):
        p = binary / name
        p.write_text(stub)
        p.chmod(0o755)
    pip = bench / 'env/bin/pip'
    pip.write_text(stub)
    pip.chmod(0o755)
    script = (Path(__file__).parents[1] / 'deploy/init.sh').read_text().replace('/workspace', str(source))
    env = dict(os.environ, PATH=str(binary)+os.pathsep+os.environ['PATH'],
               PYTHONPATH=os.pathsep.join(str(bench / 'apps' / name) for name in ('frappe','payments','lms','nightjar_learning')),
               CALL_LOG=str(tmp_path / 'calls.jsonl'),
               DB_ROOT_PASSWORD='test', ADMIN_PASSWORD='test', NIGHTJAR_VIDEO_SECRET='test')
    return work, bench, script, env


def test_recovery_reaches_start_and_restart_preserves_site(tmp_path):
    import json
    work, bench, script, env = lifecycle_fixture(tmp_path)
    for _ in range(2):
        result = subprocess.run(['bash', '-c', script], cwd=work, env=env, capture_output=True, text=True)
        assert result.returncode == 0, result.stdout+result.stderr
    calls = [json.loads(line) for line in Path(env['CALL_LOG']).read_text().splitlines()]
    assert sum(call[:2] == ['bench', 'new-site'] for call in calls) == 1
    assert sum(call[:2] == ['bench', 'build'] for call in calls) == 1
    assert sum(call == ['bench', 'start'] for call in calls) == 2
    assert (bench / 'apps/nightjar_learning/sentinel.txt').is_file()


def test_failed_build_does_not_mark_assets_complete_and_can_retry(tmp_path):
    work, bench, script, env = lifecycle_fixture(tmp_path)
    result = subprocess.run(['bash', '-c', script], cwd=work, env=dict(env, FAIL_BUILD='1'), capture_output=True, text=True)
    assert result.returncode == 9
    assert 'Building Frappe and LMS assets' in result.stderr
    assert not (bench / '.nightjar-native-assets').exists()
    assert (bench / 'sites/nightjar.localhost/site_config.json').exists()
    result = subprocess.run(['bash', '-c', script], cwd=work, env=env, capture_output=True, text=True)
    assert result.returncode == 0, result.stdout+result.stderr
    assert (bench / '.nightjar-native-assets').exists()


def test_incomplete_site_directory_is_not_overwritten(tmp_path):
    work, bench, script, env = lifecycle_fixture(tmp_path)
    site = bench / 'sites/nightjar.localhost'
    site.mkdir()
    valuable = site / 'keep.txt'
    valuable.write_text('existing data')
    result = subprocess.run(['bash', '-c', script], cwd=work, env=env, capture_output=True, text=True)
    assert result.returncode != 0
    assert 'Refusing to overwrite' in result.stderr
    assert valuable.read_text() == 'existing data'
    assert not (site / 'site_config.json').exists()


def test_changed_patch_rebuilds_native_assets(tmp_path):
    import json
    work, bench, script, env = lifecycle_fixture(tmp_path)
    subprocess.run(['bash', '-c', script], cwd=work, env=env, check=True, capture_output=True)
    (tmp_path / 'source/deploy/patches/test.patch').write_text('new reviewed asset revision')
    subprocess.run(['bash', '-c', script], cwd=work, env=env, check=True, capture_output=True)
    calls = [json.loads(line) for line in Path(env['CALL_LOG']).read_text().splitlines()]
    assert sum(call[:2] == ['bench', 'build'] for call in calls) == 2
    assert sum(call[:2] == ['bench', 'new-site'] for call in calls) == 1
