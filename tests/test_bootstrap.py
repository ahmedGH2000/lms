"""Regression for Bench's depth-one clone followed by a pinned checkout."""
from pathlib import Path
import subprocess


def run(*args):
    return subprocess.check_output(args, text=True, stderr=subprocess.STDOUT).strip()


def test_fetch_missing_pin_from_shallow_clone(tmp_path):
    origin = tmp_path / 'origin'
    clone = tmp_path / 'clone'
    run('git', 'init', str(origin))
    run('git', '-C', str(origin), 'config', 'user.email', 'test@example.invalid')
    run('git', '-C', str(origin), 'config', 'user.name', 'Bootstrap test')
    (origin / 'file.txt').write_text('pinned version')
    run('git', '-C', str(origin), 'add', 'file.txt')
    run('git', '-C', str(origin), 'commit', '-m', 'pin')
    pin = run('git', '-C', str(origin), 'rev-parse', 'HEAD')
    (origin / 'file.txt').write_text('newer version')
    run('git', '-C', str(origin), 'commit', '-am', 'advance')
    run('git', 'clone', '--depth=1', origin.as_uri(), str(clone))
    missing = subprocess.run(['git', '-C', str(clone), 'cat-file', '-e', pin+'^{commit}'], capture_output=True)
    assert missing.returncode != 0
    script = (Path(__file__).parents[1] / 'deploy/init.sh').read_text()
    function = script.split('pin_revision() {', 1)[1].split('\n}', 1)[0]
    runner = 'set -e\npin_revision() {'+function+'\n}\npin_revision "$1" "$2" "$3"'
    for _ in range(2):
        run('bash', '-c', runner, 'pin-test', str(clone), origin.as_uri(), pin)
        assert run('git', '-C', str(clone), 'rev-parse', 'HEAD') == pin
        assert (clone / 'file.txt').read_text() == 'pinned version'


def test_generated_lockfile_preserved_and_repeated_run_keeps_changes(tmp_path):
    origin = tmp_path / 'origin'
    clone = tmp_path / 'clone'
    run('git', 'init', '-b', 'version-15', str(origin))
    run('git', '-C', str(origin), 'config', 'user.email', 'test@example.invalid')
    run('git', '-C', str(origin), 'config', 'user.name', 'Bootstrap test')
    (origin / 'frontend').mkdir()
    (origin / 'frontend/yarn.lock').write_text('pinned lock')
    run('git', '-C', str(origin), 'add', '.')
    run('git', '-C', str(origin), 'commit', '-m', 'pin')
    pin = run('git', '-C', str(origin), 'rev-parse', 'HEAD')
    (origin / 'frontend/yarn.lock').write_text('newer upstream lock')
    run('git', '-C', str(origin), 'commit', '-am', 'advance')
    run('git', 'clone', '--depth=1', origin.as_uri(), str(clone))
    (clone / 'frontend/yarn.lock').write_text('generated by previous install')
    script = (Path(__file__).parents[1] / 'deploy/init.sh').read_text()
    function = script.split('pin_revision() {', 1)[1].split('\n}', 1)[0]
    runner = 'set -e\npin_revision() {' + function + '\n}\npin_revision "$1" "$2" "$3"'
    run('bash', '-c', runner, 'pin-test', str(clone), origin.as_uri(), pin)
    assert run('git', '-C', str(clone), 'rev-parse', 'HEAD') == pin
    assert (clone / 'frontend/yarn.lock').read_text() == 'pinned lock'
    assert run('git', '-C', str(clone), 'show', 'stash@{0}:frontend/yarn.lock') == 'generated by previous install'
    stash = run('git', '-C', str(clone), 'rev-parse', 'refs/stash')
    (clone / 'frontend/yarn.lock').write_text('installed at pinned version')
    run('bash', '-c', runner, 'pin-test', str(clone), origin.as_uri(), pin)
    assert (clone / 'frontend/yarn.lock').read_text() == 'installed at pinned version'
    assert run('git', '-C', str(clone), 'rev-parse', 'refs/stash') == stash


def test_source_changes_are_preserved_and_block_checkout(tmp_path):
    origin = tmp_path / 'origin'
    clone = tmp_path / 'clone'
    run('git', 'init', str(origin))
    run('git', '-C', str(origin), 'config', 'user.email', 'test@example.invalid')
    run('git', '-C', str(origin), 'config', 'user.name', 'Bootstrap test')
    (origin / 'app.py').write_text('old source')
    run('git', '-C', str(origin), 'add', '.')
    run('git', '-C', str(origin), 'commit', '-m', 'pin')
    pin = run('git', '-C', str(origin), 'rev-parse', 'HEAD')
    (origin / 'app.py').write_text('new source')
    run('git', '-C', str(origin), 'commit', '-am', 'advance')
    run('git', 'clone', '--depth=1', origin.as_uri(), str(clone))
    before = run('git', '-C', str(clone), 'rev-parse', 'HEAD')
    (clone / 'app.py').write_text('user edits')
    script = (Path(__file__).parents[1] / 'deploy/init.sh').read_text()
    function = script.split('pin_revision() {', 1)[1].split('\n}', 1)[0]
    runner = 'set -e\npin_revision() {' + function + '\n}\npin_revision "$1" "$2" "$3"'
    result = subprocess.run(['bash', '-c', runner, 'pin-test', str(clone), origin.as_uri(), pin], capture_output=True, text=True)
    assert result.returncode != 0
    assert 'Refusing to switch' in result.stderr
    assert (clone / 'app.py').read_text() == 'user edits'
    assert run('git', '-C', str(clone), 'rev-parse', 'HEAD') == before


